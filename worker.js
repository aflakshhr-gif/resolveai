const requestWindows = new Map();

const json = (body, status = 200) =>
  new Response(JSON.stringify(body), {
    status,
    headers: {
      "content-type": "application/json; charset=utf-8",
      "cache-control": "no-store",
    },
  });

function analyzeOffline(subject, messages) {
  const customerText = messages
    .filter((message) => message.from === "Customer")
    .map((message) => message.text)
    .join(" ");
  const text = (subject + " " + customerText).toLowerCase();

  const has = (words) => words.some((word) => text.includes(word));
  const urgent = has([
    "urgent", "asap", "immediately", "emergency", "can't access",
    "cannot access", "locked out", "fraud", "unauthorized", "lost",
    "broken", "not working", "angry", "法律", "cancel my account",
  ]);
  const shipping = has(["order", "tracking", "shipment", "shipping", "delivery", "package", "parcel"]);
  const account = has(["login", "log in", "sign in", "password", "account", "access"]);
  const billing = has(["billing", "bill", "charged", "charge", "refund", "payment", "invoice", "subscription", "price"]);
  const feedback = has(["feature", "suggestion", "feedback", "dark mode", "would love"]);
  const positive = has(["thank you", "thanks", "great", "appreciate", "love it", "solved", "excellent"]);
  const negative = has(["frustrated", "angry", "upset", "disappointed", "unacceptable", "problem", "issue", "haven't", "not received", "can't", "cannot"]);

  let intent = "General support";
  let next_step = "Review the conversation and ask the customer for any missing details before taking action.";
  let suggested_reply = "Thanks for reaching out. I’m happy to help. Could you share a little more detail so I can look into this for you?";

  if (shipping) {
    intent = "Order and shipping";
    next_step = "Check the order record and carrier tracking; confirm the latest verified status before replying.";
    suggested_reply = "Thanks for reaching out, and I’m sorry you haven’t received an update. I can help check this. Please allow me to review the order and its latest tracking information; I’ll share an update once the status is confirmed.";
  } else if (account) {
    intent = "Account access";
    next_step = "Verify the account through the approved support process and check the password-reset or sign-in logs.";
    suggested_reply = "I’m sorry you’re having trouble accessing your account. Please don’t share your password or verification codes. I recommend trying the account recovery process, and our team can check the sign-in issue through the approved support process.";
  } else if (billing) {
    intent = "Billing and payments";
    next_step = "Review the relevant invoice and payment records; do not promise a refund or adjustment until verified.";
    suggested_reply = "Thanks for flagging this. I understand billing questions can be frustrating. I’ll need to review the relevant invoice and payment records before confirming what happened or whether an adjustment is possible.";
  } else if (feedback) {
    intent = "Product feedback";
    next_step = "Record the suggestion with the product team and check whether it is already planned.";
    suggested_reply = "Thanks for sharing this suggestion! I appreciate you taking the time to let us know. I’ll pass the feedback to the product team for review.";
  } else if (positive) {
    intent = "Positive feedback";
    next_step = "Acknowledge the customer's feedback and close the conversation if no further help is needed.";
    suggested_reply = "You’re very welcome! I’m glad we could help. Please reach out anytime if you need anything else.";
  }

  const sentiment = positive && !negative ? "Positive" : negative ? "Frustrated / concerned" : "Neutral";
  const urgency = urgent ? "High" : (shipping || billing || account) ? "Medium" : "Low";

  if (urgent) {
    next_step = "Prioritize this conversation. Verify the issue and escalate through the team's approved process if needed.";
  }

  return {
    sentiment,
    urgency,
    intent,
    suggested_reply,
    next_step,
    mode: "offline-demo",
    disclaimer: "Rule-based demo suggestion, not generated by a language model. Verify all details before use.",
  };
}

async function analyze(request) {
  if (request.method !== "POST") {
    return json({ error: "Method not allowed." }, 405);
  }

  const origin = request.headers.get("Origin");
  if (origin && origin !== new URL(request.url).origin) {
    return json({ error: "Origin not allowed." }, 403);
  }

  const ip = request.headers.get("CF-Connecting-IP") || "unknown";
  const now = Date.now();
  const recent = (requestWindows.get(ip) || []).filter((time) => now - time < 60000);
  if (recent.length >= 8) {
    return json({ error: "Too many requests. Please wait a minute and try again." }, 429);
  }
  recent.push(now);
  requestWindows.set(ip, recent);

  let body;
  try {
    body = await request.json();
  } catch {
    return json({ error: "Invalid JSON request." }, 400);
  }

  const subject = typeof body.subject === "string" ? body.subject.slice(0, 240) : "";
  if (!Array.isArray(body.messages) || body.messages.length < 1 || body.messages.length > 12) {
    return json({ error: "Provide between 1 and 12 conversation messages." }, 400);
  }

  const messages = body.messages
    .map((message) => ({
      from: message && (message.from === "agent" || message.from === "Agent") ? "Agent" : "Customer",
      text: message && typeof message.text === "string" ? message.text.slice(0, 2000) : "",
    }))
    .filter((message) => message.text.trim());

  if (!messages.length) {
    return json({ error: "The conversation has no readable messages." }, 400);
  }

  return json(analyzeOffline(subject, messages));
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.pathname === "/api/health") {
      if (request.method !== "GET") {
        return json({ error: "Method not allowed." }, 405);
      }
      return json({
        service: "ResolveAI",
        status: "ok",
        mode: "offline-demo",
        ai_configured: false,
      });
    }
    if (url.pathname === "/api/ai") {
      return analyze(request);
    }
    return env.ASSETS.fetch(request);
  },
};
